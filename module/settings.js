/**
 * Older versions saved `portrait-directory` via the `DirectoryPicker` lib in the
 * form `[data] path/to/dir` (or `[s3:bucket] path`). The native v13+ folder picker
 * stores a bare path instead. This strips a legacy source prefix if present.
 */
function stripSourcePrefix(value) {
    const str = typeof value === 'string' ? value : '';
    const match = str.match(/^\s*\[[^\]]+\]\s*(.*)$/u);
    return (match ? match[1] : str).trim();
}
/** Whether a folder exists and is accessible in the `data` storage. */
async function folderExists(path) {
    try {
        const picker = globalThis.FilePicker ?? foundry.applications.apps.FilePicker.implementation;
        await picker.browse(artSource(), path);
        return true;
    }
    catch {
        return false;
    }
}
/**
 * One-time migration of the `portrait-directory` setting. A legacy `[data] …`
 * prefix makes the native folder picker open on an unresolvable path and warn.
 * We strip the prefix, keep the folder only if it still exists, and otherwise
 * reset to empty. GM-only, since it writes a world-scoped setting.
 */
export async function migratePortraitDirectory() {
    if (!game.user?.isGM)
        return;
    const raw = game.settings.get(MODULE, 'portrait-directory');
    if (typeof raw !== 'string')
        return;
    const stripped = stripSourcePrefix(raw);
    // No legacy prefix (or already clean): nothing to migrate.
    if (stripped === raw)
        return;
    const resolved = stripped && (await folderExists(stripped)) ? stripped : '';
    await game.settings.set(MODULE, 'portrait-directory', resolved);
}
